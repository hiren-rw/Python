# Q.3: Polymorphism with Built-in len() Function

my_string = "Python"
print("Length of string : ", len(my_string))

my_list = [10, 20, 30, 40]
print("Length of list : ", len(my_list))

my_dict = {
    "name": "Alice",
    "age": 21,
    "course": "CS"
    }
print("Length of dictionary : ", len(my_dict))